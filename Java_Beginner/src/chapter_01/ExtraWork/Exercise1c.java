public class Exercise1c {

    public static void main(String[] args) {

        // Create an integer variable named x and set its value to 5
        int x = 5;

        // Continue looping as long as x is greater than 1
        while (x > 1) {

            // Decrease the value of x by 1 each time through the loop
            x = x - 1;

            // Check whether x is less than 3
            if (x < 3) {

                // If x is less than 3, print the message
                System.out.println("small x");
            }
        }
    }
}
